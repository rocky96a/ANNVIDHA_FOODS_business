import os
import sqlite3
import sys

import psycopg
from psycopg import sql

SQLITE_DB = os.path.join(os.path.dirname(os.path.abspath(__file__)), "shop.db")
DATABASE_URL = os.environ.get("DATABASE_URL")

TABLES = [
    "products",
    "ingredients",
    "locations",
    "users",
    "staff",
    "orders",
    "stock",
    "expenses",
]

SCHEMA = """
CREATE TABLE IF NOT EXISTS products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT DEFAULT '',
    price INTEGER NOT NULL,
    mrp INTEGER DEFAULT 0,
    stock INTEGER DEFAULT 0,
    image_url TEXT DEFAULT '',
    active INTEGER DEFAULT 1,
    cost_price INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS ingredients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    note TEXT DEFAULT '',
    emoji TEXT DEFAULT '',
    photo TEXT DEFAULT ''
);

CREATE TABLE IF NOT EXISTS locations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    address TEXT DEFAULT ''
);

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    phone TEXT UNIQUE,
    email TEXT DEFAULT '',
    password_hash TEXT,
    address TEXT DEFAULT '',
    pincode TEXT DEFAULT ''
);

CREATE TABLE IF NOT EXISTS staff (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    username TEXT UNIQUE,
    password_hash TEXT,
    role TEXT,
    active INTEGER DEFAULT 1
);

CREATE TABLE IF NOT EXISTS orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    phone TEXT,
    address TEXT,
    pincode TEXT,
    items TEXT,
    total INTEGER,
    status TEXT DEFAULT 'New',
    created_at TEXT,
    user_id INTEGER,
    assigned_to INTEGER
);

CREATE TABLE IF NOT EXISTS stock (
    product_id INTEGER,
    location_id INTEGER,
    qty INTEGER DEFAULT 0,
    rack TEXT DEFAULT '',
    PRIMARY KEY (product_id, location_id)
);

CREATE TABLE IF NOT EXISTS expenses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_date TEXT NOT NULL,
    category TEXT NOT NULL,
    amount INTEGER NOT NULL CHECK (amount >= 0),
    note TEXT DEFAULT '',
    created_at TEXT NOT NULL
);
"""


def count_rows(connection, table):
    return connection.execute(
        sql.SQL("SELECT COUNT(*) FROM {}").format(sql.Identifier(table))
    ).fetchone()[0]


def main():
    if not DATABASE_URL:
        sys.exit(
            "ERROR: DATABASE_URL is not set.\n"
            "Set it privately in your terminal before running this script."
        )

    if not os.path.isfile(SQLITE_DB):
        sys.exit(f"ERROR: SQLite database not found: {SQLITE_DB}")

    sqlite_conn = sqlite3.connect(SQLITE_DB)
    sqlite_conn.row_factory = sqlite3.Row

    print("Source SQLite database:", SQLITE_DB)
    print("\nSource record counts:")

    source_data = {}
    for table in TABLES:
        rows = sqlite_conn.execute(
            f'SELECT * FROM "{table}" ORDER BY rowid'
        ).fetchall()
        source_data[table] = [dict(row) for row in rows]
        print(f"  {table}: {len(rows)}")

    try:
        with psycopg.connect(DATABASE_URL) as pg:
            with pg.cursor() as cur:
                cur.execute(SCHEMA)

                # Refuse to merge into a non-empty database.
                # This prevents accidental duplicate IDs or overwrites.
                for table in TABLES:
                    destination_count = count_rows(cur, table)
                    if destination_count:
                        raise RuntimeError(
                            f"Destination table '{table}' already has "
                            f"{destination_count} rows. Nothing was migrated. "
                            "Use a fresh/empty Neon database or inspect it first."
                        )

                for table in TABLES:
                    rows = source_data[table]
                    if not rows:
                        continue

                    columns = list(rows[0].keys())
                    insert_query = sql.SQL(
                        "INSERT INTO {} ({}) VALUES ({})"
                    ).format(
                        sql.Identifier(table),
                        sql.SQL(", ").join(map(sql.Identifier, columns)),
                        sql.SQL(", ").join(sql.Placeholder() for _ in columns),
                    )

                    for row in rows:
                        cur.execute(insert_query, [row[col] for col in columns])

                # Reset generated ID sequences so new inserts continue
                # above the preserved SQLite IDs.
                for table in TABLES:
                    if table == "stock":
                        continue

                    # Reset the identity sequence to match the largest ID.
                    cur.execute(
                        sql.SQL("SELECT COALESCE(MAX(id), 0) FROM {}").format(
                            sql.Identifier(table)
                        )
                    )
                    max_id = cur.fetchone()[0]

                    cur.execute(
                        "SELECT pg_get_serial_sequence(%s, 'id')",
                        (table,),
                    )
                    sequence_name = cur.fetchone()[0]

                    if sequence_name:
                        if max_id > 0:
                            cur.execute(
                                "SELECT setval(%s::regclass, %s, true)",
                                (sequence_name, max_id),
                            )
                        else:
                            cur.execute(
                                "SELECT setval(%s::regclass, 1, false)",
                                (sequence_name,),
                            )

            # Verify counts before committing.
            print("\nDestination record counts:")
            for table in TABLES:
                destination_count = count_rows(pg, table)
                source_count = len(source_data[table])
                print(f"  {table}: {destination_count}")
                if destination_count != source_count:
                    raise RuntimeError(
                        f"Count mismatch in {table}: "
                        f"SQLite={source_count}, PostgreSQL={destination_count}"
                    )

        print("\nSUCCESS: Migration completed and record counts match.")

    finally:
        sqlite_conn.close()


if __name__ == "__main__":
    main()
